#!/usr/bin/env bash
# ============================================================
#  AI Friend -- Offline Setup
#  Python 3.10  |  CUDA 12.1  |  RTX 3050
# ============================================================

set -euo pipefail
cd "$(dirname "$0")"

echo
echo "============================================================"
echo " AI Friend -- Offline Setup"
echo " Python 3.10  |  CUDA 12.1  |  RTX 3050"
echo "============================================================"
echo

# ─────────────────────────────────────────────────────────────
# Version matrix
#
#  torch            2.4.1+cu121
#  torchvision      0.19.1+cu121
#  torchaudio       2.4.1+cu121
#  diffusers        0.29.2
#  huggingface_hub  0.24.6        pinned -- do NOT upgrade
#  transformers     4.43.4
#  tokenizers       0.19.1
#  safetensors      0.4.3
#  accelerate       0.32.1
#  numpy            1.26.4        torch 2.4.x requires <2.0
#  pillow           10.3.0
#  imageio          2.33.1
#  imageio-ffmpeg   0.4.9
#  fastapi          0.111.0
#  uvicorn          0.29.0
#  pydantic         2.7.1
#  requests         2.31.0
#  python-dotenv    1.0.1
#
#  Models:
#  SD model : Lykon/DreamShaper          (~2 GB, excellent realism)
#  VAE      : stabilityai/sd-vae-ft-ema  (~335 MB)
#  LLM      : gurubot/girl               (Ollama)
#  GIFs     : generated by SD pipeline directly (no extra model needed)
# ─────────────────────────────────────────────────────────────

OLLAMA_MODEL="gurubot/girl"
SD_MODEL_ID="Lykon/DreamShaper"
SD_MODEL_PATH="models/dreamshaper"
VAE_MODEL_ID="stabilityai/sd-vae-ft-ema"
VAE_MODEL_PATH="models/vae"

die() { echo "ERROR: $*" >&2; exit 1; }

# ─────────────────────────────────────────────
# Step 1 -- Check Python 3.10
# ─────────────────────────────────────────────
echo "[Step 1] Checking Python..."
python3.10 --version > /dev/null 2>&1 || die "Python 3.10 not found. Install with:
  sudo apt update && sudo apt install -y python3.10 python3.10-venv python3.10-dev"

PY_VER=$(python3.10 --version 2>&1 | awk '{print $2}')
PY_MAJOR_MINOR=$(echo "$PY_VER" | cut -d. -f1,2)
[[ "$PY_MAJOR_MINOR" == "3.10" ]] || die "Python 3.10.x required, found $PY_VER."
echo "Python $PY_VER -- OK"

# ─────────────────────────────────────────────
# Step 2 -- Virtual environment
# ─────────────────────────────────────────────
echo
echo "[Step 2] Setting up virtual environment..."
if [[ ! -d venv ]]; then
    python3.10 -m venv venv || die "venv creation failed."
    echo "Virtual environment created."
else
    echo "Virtual environment already exists -- skipping."
fi
# shellcheck disable=SC1091
source venv/bin/activate || die "Could not activate venv."

# ─────────────────────────────────────────────
# Step 3 -- Upgrade pip + build tools
# ─────────────────────────────────────────────
echo
echo "[Step 3] Upgrading pip and build tools..."
python -m pip install --upgrade pip setuptools wheel --quiet
echo "Done."

# ─────────────────────────────────────────────
# Step 4 -- Wipe conflicting packages
# ─────────────────────────────────────────────
echo
echo "[Step 4] Removing any conflicting existing packages..."
(
    pip uninstall torch torchvision torchaudio \
        diffusers transformers huggingface_hub \
        tokenizers safetensors accelerate \
        -y --quiet 2>/dev/null
) || true
echo "Done (errors above are harmless if packages did not exist)."

# ─────────────────────────────────────────────
# Step 5 -- PyTorch 2.4.1 + CUDA 12.1
# ─────────────────────────────────────────────
echo
echo "[Step 5] Installing PyTorch 2.4.1 (CUDA 12.1) -- ~2.5 GB..."
pip install \
    torch==2.4.1+cu121 \
    torchvision==0.19.1+cu121 \
    torchaudio==2.4.1+cu121 \
    --index-url https://download.pytorch.org/whl/cu121 \
    --quiet || die "PyTorch install failed."
echo "PyTorch 2.4.1+cu121 installed."

# ─────────────────────────────────────────────
# Step 6 -- Verify CUDA
# ─────────────────────────────────────────────
echo
echo "[Step 6] Verifying CUDA..."
python -c "
import torch
c = torch.cuda.is_available()
print('  CUDA available :', c)
print('  GPU            :', torch.cuda.get_device_name(0) if c else 'None')
print('  Torch version  :', torch.__version__)
" || echo "WARNING: CUDA check failed -- will fall back to CPU."

# ─────────────────────────────────────────────
# Step 7 -- ML dependencies (strict order)
# ─────────────────────────────────────────────
echo
echo "[Step 7] Installing ML dependencies (strict order)..."

echo "  [7a] numpy, pillow..."
pip install numpy==1.26.4 pillow==10.3.0 --quiet || die "numpy/pillow failed."

echo "  [7b] huggingface_hub 0.24.6 (pinned -- do NOT upgrade)..."
pip install huggingface_hub==0.24.6 --quiet || die "huggingface_hub failed."

echo "  [7c] tokenizers, safetensors..."
pip install tokenizers==0.19.1 safetensors==0.4.3 --quiet || die "tokenizers/safetensors failed."

echo "  [7d] transformers..."
pip install transformers==4.43.4 --quiet || die "transformers failed."

echo "  [7e] accelerate..."
pip install accelerate==0.32.1 --quiet || die "accelerate failed."

echo "  [7f] diffusers 0.29.2..."
pip install diffusers==0.29.2 --quiet || die "diffusers failed."

echo "  [7g] imageio (used by PIL GIF assembly)..."
pip install imageio==2.33.1 imageio-ffmpeg==0.4.9 --quiet || die "imageio failed."

echo "  ML dependencies installed."

# ─────────────────────────────────────────────
# Step 8 -- API dependencies
# ─────────────────────────────────────────────
echo
echo "[Step 8] Installing API dependencies..."
pip install \
    pydantic==2.7.1 \
    fastapi==0.111.0 \
    "uvicorn[standard]==0.29.0" \
    requests==2.31.0 \
    python-dotenv==1.0.1 \
    --quiet || die "API dependencies failed."
echo "  API dependencies installed."

# ─────────────────────────────────────────────
# Step 9 -- Smoke-test all imports
# ─────────────────────────────────────────────
echo
echo "[Step 9] Smoke-testing all imports..."
python -c "
import torch, diffusers, transformers, accelerate, huggingface_hub
import fastapi, uvicorn, dotenv, imageio
from PIL import Image
print('  torch:       ', torch.__version__)
print('  diffusers:   ', diffusers.__version__)
print('  fastapi:     ', fastapi.__version__)
c = torch.cuda.is_available()
print('  CUDA ready:  ', c)
print('All imports OK.')
" || die "Import smoke-test failed -- fix errors above before continuing."

# ─────────────────────────────────────────────
# Step 10 -- Ollama check
# ─────────────────────────────────────────────
echo
echo "[Step 10] Checking Ollama..."
command -v ollama > /dev/null 2>&1 || die "Ollama not found. Download from https://ollama.com/download"
echo "  Ollama executable found."

curl -sf http://localhost:11434/ > /dev/null 2>&1 || die "Ollama service is not running.
Start it with: ollama serve   (in a separate terminal)"

if ! ollama list | grep -qiF "$OLLAMA_MODEL"; then
    echo "Pulling \"$OLLAMA_MODEL\"..."
    ollama pull "$OLLAMA_MODEL" || die "Ollama pull failed."
    echo "Ollama model ready."
else
    echo "Ollama model \"$OLLAMA_MODEL\" already present -- skipping."
fi

python -c "
import requests
r = requests.post('http://localhost:11434/api/generate',
    json={'model':'$OLLAMA_MODEL','prompt':'hi','stream':False}, timeout=30)
r.raise_for_status()
print('  Ollama API -- OK')
" || die "Ollama API test failed."

# ─────────────────────────────────────────────
# Step 11 -- DreamShaper SD model (~2 GB)
# ─────────────────────────────────────────────
echo
echo "[Step 11] Checking DreamShaper model..."
if [[ ! -f "$SD_MODEL_PATH/model_index.json" ]]; then
    echo "Downloading DreamShaper to $SD_MODEL_PATH/ -- ~2 GB..."
    SD_MODEL_ID="$SD_MODEL_ID" SD_MODEL_PATH="$SD_MODEL_PATH" \
    python -c "
import os
from diffusers import StableDiffusionPipeline
pipe = StableDiffusionPipeline.from_pretrained(os.environ['SD_MODEL_ID'])
pipe.save_pretrained(os.environ['SD_MODEL_PATH'])
print('SD model saved.')
" || die "SD model download failed."
    echo "DreamShaper model downloaded."
else
    echo "DreamShaper model already present -- skipping."
fi

# ─────────────────────────────────────────────
# Step 12 -- VAE model (~335 MB)
# ─────────────────────────────────────────────
echo
echo "[Step 12] Checking VAE model (EMA edition for sharpness)..."
if [[ ! -f "$VAE_MODEL_PATH/config.json" ]]; then
    echo "Downloading VAE to $VAE_MODEL_PATH/ -- ~335 MB..."
    VAE_MODEL_ID="$VAE_MODEL_ID" VAE_MODEL_PATH="$VAE_MODEL_PATH" \
    python -c "
import os
from diffusers import AutoencoderKL
vae = AutoencoderKL.from_pretrained(os.environ['VAE_MODEL_ID'])
vae.save_pretrained(os.environ['VAE_MODEL_PATH'])
print('VAE saved.')
" || die "VAE download failed."
    echo "VAE EMA downloaded."
else
    echo "VAE EMA already present -- skipping."
fi

# ─────────────────────────────────────────────
# Step 13 -- AnimateDiff not used
# ─────────────────────────────────────────────
echo
echo "[Step 13] AnimateDiff not used -- GIFs use SD pipeline directly. Skipping."

# ─────────────────────────────────────────────
# Step 14 -- backend/.env (always overwrite)
# ─────────────────────────────────────────────
echo
echo "[Step 14] Writing backend/.env..."
mkdir -p backend
cat > backend/.env <<EOF
BASE_URL=http://127.0.0.1:8000
OLLAMA_URL=http://localhost:11434/api/generate
MODEL_NAME=$OLLAMA_MODEL
SD_PATH=models/dreamshaper
VAE_PATH=models/vae
EOF
echo "backend/.env written:"
cat backend/.env

# ─────────────────────────────────────────────
# Step 15 -- ai-friend/.env (only if missing)
# ─────────────────────────────────────────────
echo
echo "[Step 15] Creating ai-friend/.env..."
if [[ ! -f "ai-friend/.env" ]]; then
    mkdir -p ai-friend
    echo "REACT_APP_API_URL=http://127.0.0.1:8000" > ai-friend/.env
    echo "ai-friend/.env created."
else
    echo "ai-friend/.env already exists -- skipping."
fi

# ─────────────────────────────────────────────
# Step 16 -- npm install
# ─────────────────────────────────────────────
echo
echo "[Step 16] Installing React dependencies in ai-friend/..."
if ! command -v npm > /dev/null 2>&1; then
    echo "WARNING: npm not found -- skipping React install."
    echo "Install Node.js 18+ with:"
    echo "  curl -fsSL https://deb.nodesource.com/setup_18.x | sudo -E bash -"
    echo "  sudo apt install -y nodejs"
    echo "Then run:"
    echo "  cd ai-friend && npm install && npm install @mui/icons-material"
else
    (
        cd ai-friend
        echo "  Running npm install..."
        npm install --silent
        echo "  Installing MUI icons..."
        npm install @mui/icons-material --silent
    ) || die "npm install failed."
    echo "  React dependencies installed."
fi

# ─────────────────────────────────────────────
# Done
# ─────────────────────────────────────────────
echo
echo "============================================================"
echo " Setup complete!"
echo
echo " Python packages:"
echo "   torch            2.4.1+cu121"
echo "   diffusers        0.29.2"
echo "   huggingface_hub  0.24.6  <-- do NOT pip upgrade this"
echo "   transformers     4.43.4"
echo "   accelerate       0.32.1"
echo "   numpy            1.26.4"
echo "   imageio          2.33.1"
echo "   fastapi          0.111.0  /  uvicorn 0.29.0"
echo "   pydantic         2.7.1"
echo
echo " Models downloaded:"
echo "   LLM  : $OLLAMA_MODEL                (Ollama)"
echo "   SD   : DreamShaper                  (models/dreamshaper/)"
echo "   VAE  : sd-vae-ft-ema                (models/vae/)"
echo "   GIFs : SD pipeline (4 frames, no extra model needed)"
echo
echo " IMPORTANT: Do NOT run 'pip install --upgrade' on this venv."
echo " huggingface_hub is intentionally pinned at 0.24.6."
echo
echo " To start the app:"
echo "   Terminal 1:  ./startbot.sh"
echo "   Terminal 2:  cd ai-friend && npm start"
echo
echo " GIF keywords: gif, animate, dancing, walking, moving,"
echo "               motion, video, action"
echo " Image keywords: image, picture, photo, pic, show me, draw"
echo "============================================================"
